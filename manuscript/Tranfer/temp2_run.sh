#!/bin/bash

# --- Input Validation ---
if [ "$#" -lt 2 ] || [ "$#" -gt 4 ]; then
    echo "Usage: $0 <discovery_epochs> <hpc_compute_epochs> [mode] [scorer]"
    echo "  mode:   'all' (default) or 'subset' (runs ONLY Control_Continuted and Dynamic_Region_All_Combined)"
    echo "  scorer: local_dev (default) | percentile | cv | change | cka"
    echo "Example: $0 50 100 subset change"
    exit 1
fi

EPOCHS=$1
PRETRAIN=$2
MODE=${3:-all} # Defaults to 'all' if no 3rd argument is provided
SCORER=${4:-local_dev} # Stage-2 universe the discovered-regions map belongs to

case "$SCORER" in
    local_dev|percentile|cv|change|cka) ;;
    all)
        echo "Error: scorer 'all' is discovery-only. Re-run stage 1 with an explicit scorer" >&2
        echo "(e.g. './temp1_run.sh $EPOCHS $PRETRAIN change'), then that scorer's stage 2." >&2
        exit 1
        ;;
    *) echo "Error: unknown scorer '$SCORER' (expected local_dev|percentile|cv|change|cka)" >&2; exit 1 ;;
esac

echo "    Scorer universe: $SCORER"

# Scorer directory infix, mirroring transfer.py's scorer_suffix():
# default scorer keeps the legacy unsuffixed universe; others use _scorer{S}.
SCORER_INFIX=""
if [ "$SCORER" != "local_dev" ]; then
    SCORER_INFIX="_scorer${SCORER}"
fi

#models=("MobileNet")
models=("ConvNeXt" "MobileNet" "InceptionNet" "XceptionNet" "RegNetX_400MF" "VGG16")
datasets=("tinyimagenet" "Cifar10" "Cifar100")
quant=("False" "True")

echo "=== Submitting Stage 2: Parallel HPC Execution ==="
echo "    Discovery Budget (Epochs): $EPOCHS | HPC Target (Pretrain): $PRETRAIN | Mode: $MODE"

for model in "${models[@]}"; do
    for dataset in "${datasets[@]}"; do
        for flag in "JF"; do
            
            # Locate the JSON file created by Stage 1 (scorer-infixed for
            # non-default universes; legacy name for the default scorer).
            # local_dev additionally falls back to the suffixed ablation map
            # written by a stage-1 'all' run when the legacy file is absent.
            if [ "$SCORER" = "local_dev" ]; then
                json_file="${model}_${dataset}_epochs${EPOCHS}_pretrain${PRETRAIN}_${flag}_discovered_regions.json"
                if [ ! -f "$json_file" ]; then
                    suffixed="${model}_${dataset}_epochs${EPOCHS}_pretrain${PRETRAIN}_scorer${SCORER}_${flag}_discovered_regions.json"
                    if [ -f "$suffixed" ]; then
                        json_file="$suffixed"
                        echo "[INFO] Using ablation-derived map: $json_file"
                    fi
                fi
            else
                json_file="${model}_${dataset}_epochs${EPOCHS}_pretrain${PRETRAIN}_scorer${SCORER}_${flag}_discovered_regions.json"
            fi
            
            if [ ! -f "$json_file" ]; then
                echo "[WARN] Waiting for $json_file to be generated by Stage 1... Skipping."
                continue
            fi

            # Read the dynamic experiment names out of the JSON file directly (will inherently include 'Control')
            mapfile -t dynamic_experiments < <(python -c "import json; print('\n'.join(json.load(open('$json_file')).keys()))")

            # Status_Map is display metadata (a dict, not a layer range) and Control
            # is trained during Stage 1 — neither is a valid stage-2 collapse target;
            # Status_Map would pass the membership check then crash _make_compression_set.
            mapfile -t dynamic_experiments < <(printf '%s\n' "${dynamic_experiments[@]}" | grep -vx -e "Status_Map" -e "Control" || true)

            # Legacy single-set maps carry no Dynamic_Region_All_Combined key
            # (discovery only exported it for >1 sets). With exactly one Set,
            # Set_0 *is* the combined target: let it through the subset filter.
            # It writes final_JF_Set_0*_whole.pt, which Transfer2's Set_0
            # fallback consumes. Status_Map stays filtered below.
            single_set_target=0
            if ! printf '%s\n' "${dynamic_experiments[@]}" | grep -qx "Dynamic_Region_All_Combined"; then
                n_sets=$(printf '%s\n' "${dynamic_experiments[@]}" | grep -c '^Set_' || true)
                if [ "$n_sets" -eq 1 ]; then
                    single_set_target=1
                    echo "[INFO] Single-set map without All_Combined — subset will submit Set_0 as the combined target"
                fi
            fi

            for quant_flag in "${quant[@]}"; do
                for experiment in "${dynamic_experiments[@]}"; do
                    
                    # --- Mode Filtering Logic ---
                    if [ "$MODE" = "subset" ]; then
                        if [[ "$experiment" != "Control_Continuted" && "$experiment" != "Dynamic_Region_All_Combined" ]]; then
                            # Single-set maps: Set_0 stands in as the combined target
                            [[ "$single_set_target" == "1" && "$experiment" == "Set_0" ]] || continue
                        fi
                    fi

                    # --- Skip completed experiments: same marker transfer.py checks at runtime
                    #     (glob the exact scorer universe's checkpoints dir so a finished
                    #     default universe cannot suppress scorer universes or vice versa) ---
                    qtag=""
                    if [ "$quant_flag" == "True" ]; then
                        qtag="_quant"
                    fi
                    if [ -n "$SCORER_INFIX" ]; then
                        done_match=$(compgen -G "${model}_${dataset}_*${SCORER_INFIX}_epochs${EPOCHS}_pretrain${PRETRAIN}/checkpoints/final_JF_${experiment}${qtag}.pt" | head -n1)
                    else
                        # Default universe has no _scorer infix — exclude suffixed dirs explicitly
                        done_match=$(compgen -G "${model}_${dataset}_*_epochs${EPOCHS}_pretrain${PRETRAIN}/checkpoints/final_JF_${experiment}${qtag}.pt" | grep -v "_scorer" | head -n1)
                    fi
                    if [ -n "$done_match" ]; then
                        echo "[SKIP] $model/$dataset/$experiment quant=$quant_flag — final artifact exists"
                        continue
                    fi

                    # Fire off the true parallel compute jobs
                    command="qsub -q all.q -l ngpus=1 -v MODEL=\"$model\",DATASET=\"$dataset\",EXPERIMENT=\"$experiment\",FLAG=\"$flag\",QUANT=\"$quant_flag\",EPOCHS=\"$EPOCHS\",PRETRAIN=\"$PRETRAIN\",SCORER=\"$SCORER\" submit_job.pbs"
                    
                    echo "Executing: $command"
                    eval "$command"
                    
                done
            done

        done
    done
done
